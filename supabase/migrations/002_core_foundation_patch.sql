-- 1. ADD preferred_brand_id TO profiles
-- ============================================================
alter table public.profiles
  add column if not exists preferred_brand_id integer
  references public.brands(id) on delete set null;

comment on column public.profiles.preferred_brand_id is
  'UX hint for login redirect. NOT permission source of truth. Access is validated through user_brand_memberships.';

create index if not exists idx_profiles_preferred_brand
  on public.profiles(preferred_brand_id)
  where preferred_brand_id is not null;

-- 2. ADD default branch support
-- ============================================================
alter table public.user_branch_access
  add column if not exists is_default boolean not null default false;

create unique index if not exists uq_uba_default_branch
  on public.user_branch_access(membership_id)
  where is_default = true;

comment on column public.user_branch_access.is_default is
  'At most one row per membership_id can have is_default = true. Enforced by partial unique index uq_uba_default_branch.';

-- 3. ADD request_id TO audit_logs
-- ============================================================
alter table public.audit_logs
  add column if not exists request_id uuid;

create index if not exists idx_al_request_id
  on public.audit_logs(request_id)
  where request_id is not null;

comment on column public.audit_logs.request_id is
  'UUID generated by application to group audit entries from one business action.';

