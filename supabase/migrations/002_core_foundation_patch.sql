-- ============================================================
-- 6. EXPLANATION: system cash account unique index
-- ============================================================
-- The index from 001:
--   CREATE UNIQUE INDEX uq_pa_system_cash
--     ON payment_accounts(brand_id, branch_id)
--     WHERE is_system_account = true AND is_cash_account = true AND branch_id IS NOT NULL;
--
-- This enforces "AT MOST ONE" system cash account per (brand_id, branch_id).
-- It does NOT enforce "exactly one." Existence is the responsibility of:
--   a) create_default_cash_account_for_branch() -- called on branch creation
--   b) Seed/init process -- for existing branches
--   c) Application logic -- creating a branch must call this function
--
-- If a row is deleted or deactivated, the constraint allows a new one.
-- It only prevents DUPLICATE system cash accounts.
-- ============================================================


-- ============================================================
-- 7. EXPLANATION: account_sequence for movement ordering
-- ============================================================
-- Tradeoff analysis for adding account_sequence to payment_account_movements:
--
-- WITHOUT account_sequence:
--   + No additional storage (saves 8 bytes per row + index)
--   + Simpler insert function
--   + Ordering uses (created_at, id) with UUID tiebreaker
--   + FOR UPDATE lock in add_payment_account_movement() serializes inserts
--     per account, so created_at collisions are practically impossible
--   - UUID v4 ordering is not strictly chronological as tiebreaker
--   - Cross-account ordering is not deterministic
--
-- WITH account_sequence:
--   + Perfect ordering: 1, 2, 3, ... per account
--   + No tiebreaker ambiguity
--   + Natural index clustering
--   - Requires BIGINT column + per-account counter logic
--   - Adds complexity to add_payment_account_movement() function
--   - Counter reset/overflow considerations
--
-- DECISION: Skip account_sequence for now.
--   The FOR UPDATE lock guarantees serial access per account.
--   Use ORDER BY created_at ASC, id ASC for all movement queries.
--   If ordering issues arise, add account_sequence as a later migration.
-- ============================================================


